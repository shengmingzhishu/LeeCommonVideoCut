"""
Output Manager - 输出管理器
管理分析产物的输出目录、文件写入和 .gitignore 配置
"""

import json
import shutil
from pathlib import Path
from typing import Dict, Any, Optional
from datetime import datetime


class OutputManager:
    """分析产物输出管理器"""

    DEFAULT_OUTPUT_DIR = ".project-analysis"

    def __init__(
        self,
        project_root: Path,
        output_dir: Optional[str] = None,
        overwrite: bool = False,
    ):
        """
        初始化输出管理器

        Args:
            project_root: 项目根目录
            output_dir: 输出目录（默认为 .project-analysis）
            overwrite: 是否覆盖最新的分析（默认保留历史）
        """
        self.project_root = Path(project_root)
        self.overwrite = overwrite

        # 解析输出目录
        if output_dir is None or output_dir == "auto":
            self.output_base = self.project_root / self.DEFAULT_OUTPUT_DIR
        else:
            self.output_base = Path(output_dir).resolve()
            # 如果是相对路径，相对于项目根目录
            if not self.output_base.is_absolute():
                self.output_base = self.project_root / self.output_base

        # 创建当前分析的输出目录
        self.current_output_dir = self._create_output_dir()

        # 自动创建 .gitignore
        self._ensure_gitignore()

    def _create_output_dir(self) -> Path:
        """创建当前分析的输出目录"""
        # 创建基础目录
        self.output_base.mkdir(parents=True, exist_ok=True)

        if self.overwrite:
            # 覆盖模式：删除最近的，创建新的
            latest = self._get_latest_analysis_dir()
            if latest and latest.exists():
                try:
                    shutil.rmtree(latest)
                except Exception:
                    pass

        # 创建新的时间戳目录
        timestamp = datetime.now().strftime("%Y-%m-%d-%H-%M-%S")
        output_dir = self.output_base / timestamp
        output_dir.mkdir(exist_ok=True)

        return output_dir

    def _get_latest_analysis_dir(self) -> Optional[Path]:
        """获取最新的分析目录"""
        try:
            dirs = [d for d in self.output_base.iterdir() if d.is_dir() and not d.name.startswith('.')]
            if not dirs:
                return None

            # 按名称排序（时间戳）
            dirs.sort(key=lambda d: d.name, reverse=True)
            return dirs[0]
        except Exception:
            return None

    def _ensure_gitignore(self):
        """确保 .gitignore 存在并包含输出目录"""
        gitignore_path = self.output_base / ".gitignore"

        if not gitignore_path.exists():
            gitignore_path.write_text("# Auto-generated by project-analysis\n", encoding="utf-8")
        else:
            # 确保 .gitignore 包含必要的忽略规则
            content = gitignore_path.read_text(encoding="utf-8")
            if "*" not in content:
                gitignore_path.write_text(
                    content + f"\n# Ignore all analysis history except .gitignore\n*\n",
                    encoding="utf-8",
                )

    def write_artifact(self, filename: str, content: str) -> Path:
        """
        写入文本产物

        Args:
            filename: 文件名
            content: 文件内容

        Returns:
            文件路径
        """
        filepath = self.current_output_dir / filename
        filepath.write_text(content, encoding="utf-8")
        return filepath

    def write_binary(self, filename: str, data: bytes) -> Path:
        """
        写入二进制文件（如图片、Excel）

        Args:
            filename: 文件名
            data: 二进制数据

        Returns:
            文件路径
        """
        filepath = self.current_output_dir / filename
        filepath.write_bytes(data)
        return filepath

    def write_json(self, filename: str, data: Dict[str, Any]) -> Path:
        """
        写入 JSON 文件

        Args:
            filename: 文件名
            data: JSON 数据

        Returns:
            文件路径
        """
        filepath = self.current_output_dir / filename
        filepath.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
        return filepath

    def get_output_summary(self) -> Dict[str, Any]:
        """获取输出摘要"""
        try:
            file_count = sum(1 for _ in self.current_output_dir.rglob("*") if _.is_file())
        except Exception:
            file_count = 0

        return {
            "output_base": str(self.output_base),
            "current_dir": str(self.current_output_dir),
            "mode": "overwrite" if self.overwrite else "history",
            "file_count": file_count,
            "relative_path": str(self.current_output_dir.relative_to(self.project_root)),
        }

    def cleanup_old_analyses(self, keep_days: int = 30):
        """
        清理旧的分析记录

        Args:
            keep_days: 保留的天数
        """
        if not self.output_base.exists():
            return

        cutoff_date = datetime.now().timestamp() - (keep_days * 86400)

        for item in self.output_base.iterdir():
            if item.is_dir() and not item.name.startswith('.'):
                try:
                    # 尝试解析时间戳
                    dir_name = item.name.replace("-", "")
                    dir_date = datetime.strptime(dir_name[:14], "%Y%m%d%H%M%S").timestamp()

                    if dir_date < cutoff_date:
                        shutil.rmtree(item)
                        print(f"已清理旧分析: {item.name}")
                except Exception:
                    # 解析失败，跳过
                    pass
